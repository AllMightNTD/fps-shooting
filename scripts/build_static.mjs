/**
 * Zero-dependency static bundle builder for Cloudflare Pages / CDN deployment.
 * Assembles public HTML/JS/assets, shared protocol/weapons, maps JSON, sound, and .glb models
 * into `dist-static/` with `_headers` caching rules and optional `FPS_WS_URL` injection.
 *
 * Usage:
 *   FPS_WS_URL="wss://your-fps-server.onrender.com/ws" node scripts/build_static.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { sanitizeWsUrl } from "../public/js/net_utils.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
export const REPO_ROOT = path.resolve(__dirname, "..");

const CLOUDFLARE_HEADERS = `# Auto-generated by scripts/build_static.mjs
/*
  X-Content-Type-Options: nosniff

/model/dist/*
  Cache-Control: public, max-age=86400

/sound/*
  Cache-Control: public, max-age=86400

/assets/*
  Cache-Control: public, max-age=86400

/shared/maps/*
  Cache-Control: public, max-age=86400

/js/*
  Cache-Control: public, max-age=300
`;

function copyMatchingFilesRecursive(srcDir, destDir, predicate) {
  let count = 0;
  let bytes = 0;
  if (!fs.existsSync(srcDir)) return { count, bytes };
  fs.mkdirSync(destDir, { recursive: true });
  for (const entry of fs.readdirSync(srcDir, { withFileTypes: true })) {
    const srcPath = path.join(srcDir, entry.name);
    const dstPath = path.join(destDir, entry.name);
    if (entry.isDirectory()) {
      const sub = copyMatchingFilesRecursive(srcPath, dstPath, predicate);
      count += sub.count;
      bytes += sub.bytes;
    } else if (entry.isFile() && predicate(entry.name, srcPath)) {
      fs.mkdirSync(path.dirname(dstPath), { recursive: true });
      fs.copyFileSync(srcPath, dstPath);
      count++;
      bytes += fs.statSync(dstPath).size;
    }
  }
  return { count, bytes };
}

export function injectWsMetaUrl(htmlText, wsUrl) {
  if (!wsUrl) return htmlText;
  const metaPattern = /<meta\s+name=["']fps-ws-url["']\s+content=["'][^"']*["']\s*\/?>/i;
  const replacement = `<meta name="fps-ws-url" content="${wsUrl}" />`;
  if (metaPattern.test(htmlText)) {
    return htmlText.replace(metaPattern, replacement);
  }
  return htmlText.replace(/<head>/i, `<head>\n    ${replacement}`);
}

export function buildStaticSite({
  rootDir = REPO_ROOT,
  outDir = path.join(rootDir, "dist-static"),
  wsUrl = process.env.FPS_WS_URL || "",
} = {}) {
  const resolvedRoot = path.resolve(rootDir);
  const resolvedOut = path.resolve(outDir);

  if (
    resolvedOut === resolvedRoot ||
    resolvedOut === path.parse(resolvedOut).root ||
    resolvedRoot.startsWith(resolvedOut + path.sep)
  ) {
    throw new Error(`Refusing unsafe outDir: ${resolvedOut}`);
  }

  let normalizedWsUrl = "";
  if (typeof wsUrl === "string" && wsUrl.trim()) {
    const clean = sanitizeWsUrl(wsUrl);
    if (!clean) {
      throw new Error(`Invalid FPS_WS_URL (must be ws:// or wss://): ${wsUrl}`);
    }
    normalizedWsUrl = clean;
  }

  fs.rmSync(resolvedOut, { recursive: true, force: true });
  fs.mkdirSync(resolvedOut, { recursive: true });

  let fileCount = 0;
  let totalBytes = 0;

  // 1. HTML entrypoints (index.html + FPS.html)
  const rawHtml = fs.readFileSync(path.join(resolvedRoot, "public", "FPS.html"), "utf8");
  const finalHtml = injectWsMetaUrl(rawHtml, normalizedWsUrl);
  for (const name of ["index.html", "FPS.html"]) {
    const target = path.join(resolvedOut, name);
    fs.writeFileSync(target, finalHtml, "utf8");
    fileCount++;
    totalBytes += Buffer.byteLength(finalHtml, "utf8");
  }

  // 2. Frontend JS modules + shared protocol.js & weapons.js
  const jsStats = copyMatchingFilesRecursive(
    path.join(resolvedRoot, "public", "js"),
    path.join(resolvedOut, "js"),
    (name) => name.endsWith(".js"),
  );
  fileCount += jsStats.count;
  totalBytes += jsStats.bytes;

  for (const sharedName of ["protocol.js", "weapons.js"]) {
    const src = path.join(resolvedRoot, "server", sharedName);
    const dst = path.join(resolvedOut, "js", sharedName);
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    fs.copyFileSync(src, dst);
    fileCount++;
    totalBytes += fs.statSync(dst).size;
  }

  // 3. Public image assets (.webp/.png/.jpg)
  const assetStats = copyMatchingFilesRecursive(
    path.join(resolvedRoot, "public", "assets"),
    path.join(resolvedOut, "assets"),
    (name) => /\.(webp|png|jpe?g)$/i.test(name),
  );
  fileCount += assetStats.count;
  totalBytes += assetStats.bytes;

  // 4. Shared map JSON layouts & colliders
  const mapStats = copyMatchingFilesRecursive(
    path.join(resolvedRoot, "shared", "maps"),
    path.join(resolvedOut, "shared", "maps"),
    (name) => name.endsWith(".json"),
  );
  fileCount += mapStats.count;
  totalBytes += mapStats.bytes;

  // 5. Sound effects & lobby music (.wav/.mp3)
  const soundStats = copyMatchingFilesRecursive(
    path.join(resolvedRoot, "sound"),
    path.join(resolvedOut, "sound"),
    (name) => /\.(wav|mp3)$/i.test(name),
  );
  fileCount += soundStats.count;
  totalBytes += soundStats.bytes;

  // 6. Built binary 3D models (.glb only; skips bulky Base64 .bundle.js)
  const modelStats = copyMatchingFilesRecursive(
    path.join(resolvedRoot, "model", "dist"),
    path.join(resolvedOut, "model", "dist"),
    (name) => name.endsWith(".glb"),
  );
  fileCount += modelStats.count;
  totalBytes += modelStats.bytes;

  // 7. Cloudflare Pages _headers
  const headersPath = path.join(resolvedOut, "_headers");
  fs.writeFileSync(headersPath, CLOUDFLARE_HEADERS, "utf8");
  fileCount++;
  totalBytes += Buffer.byteLength(CLOUDFLARE_HEADERS, "utf8");

  return {
    outDir: resolvedOut,
    wsUrl: normalizedWsUrl,
    fileCount,
    totalBytes,
  };
}

function parseArgs(argv) {
  let outDir;
  let wsUrl = process.env.FPS_WS_URL || "";
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--out-dir" && argv[i + 1]) {
      outDir = argv[++i];
    } else if (argv[i] === "--ws-url" && argv[i + 1]) {
      wsUrl = argv[++i];
    }
  }
  return { outDir, wsUrl };
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const { outDir, wsUrl } = parseArgs(process.argv.slice(2));
  const res = buildStaticSite({ outDir, wsUrl });
  const mb = (res.totalBytes / (1024 * 1024)).toFixed(2);
  console.log(
    `[build_static] Built ${res.fileCount} files (${mb} MB) -> ${res.outDir}` +
      (res.wsUrl ? ` (FPS_WS_URL=${res.wsUrl})` : " (same-origin WS fallback)"),
  );
}

